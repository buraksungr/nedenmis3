const basePaths =
  '<path d="M100 500Q180 350 260 500L240 580H110Z" fill="#d2f4ee"/>' +
  '<path d="M310 500Q400 350 490 500L470 580H320Z" fill="#75d6d2"/>' +
  '<path d="M550 500Q640 350 730 500L710 580H560Z" fill="#e9cda0"/>';
const effects =
  '<path id="current" d="M80 850H950" fill="none" stroke="#fff" stroke-width="8" data-anim="flow" data-duration="2"/>' +
  '<circle cx="200" cy="950" r="8" data-anim="pulse"/>' +
  '<circle cx="400" cy="950" r="8" data-anim="dilate"/>';
const svg = (main: string, fx = effects) =>
  `<svg viewBox="0 0 1080 1920"><g id="layer-bg"><rect width="1080" height="1920" fill="#123"/></g><g id="layer-main">${main}</g><g id="layer-fx">${fx}</g></svg>`;
const ref = { kind: 'objects-v2', title: 'Bilimsel Sahne', digest: 'centered-test' } as MotionRef;

test('dilate, pulse and flow round-trip, loop from frame zero and require a drawable stroke', () => {
  const parsed = parseStage(svg(basePaths));
  assert.equal(parsed.actors, 3);
  assert.equal(parseStage(parsed.canonical).canonical, parsed.canonical);
  const render = (frame: number) =>
    renderToStaticMarkup(createElement(ObjectScene, { scene: { ref, stage: parsed.root }, frame }));
  const a = render(0),
    b = render(15);
  assert.match(a, /transform-box:fill-box;transform-origin:center;transform:scale\(1\)/);
  assert.match(b, /stroke-dasharray="0.22 0.12"/);
  assert.match(a, /stroke-dashoffset="0"/);
  assert.match(b, /stroke-dashoffset="-0.085"/);
  assert.throws(
    () => parseStage(svg(basePaths, effects.replace('stroke="#fff"', 'stroke="none"'))),
    /flow için görünür stroke/,
  );
  for (const invisible of [
    effects.replace('stroke="#fff"', 'stroke="#fff0"'),
    effects.replace('stroke="#fff"', 'stroke="#fff" stroke-opacity="0"'),
    effects.replace('stroke-width="8"', 'stroke-width="0"'),
    effects
      .replace('<path id="current"', '<g stroke-opacity="0"><path id="current"')
      .replace('data-duration="2"/>', 'data-duration="2"/></g>'),
    effects
      .replace('<path id="current"', '<g stroke-width="0"><path id="current"')
      .replace('stroke-width="8" ', '')
      .replace('data-duration="2"/>', 'data-duration="2"/></g>'),
  ])
    assert.throws(() => parseStage(svg(basePaths, invisible)), /flow için görünür stroke/);
  const hiddenGroup =
    '<g data-anim="flow" stroke="#fff"><path d="M100 700H400" opacity="0"/></g>' +
    '<circle cx="200" cy="950" r="8" data-anim="pulse"/><circle cx="400" cy="950" r="8" data-anim="dilate"/>';
  assert.throws(() => parseStage(svg(basePaths, hiddenGroup)), /flow için görünür stroke/);
  assert.throws(
    () =>
      parseStage(
        svg(
          basePaths,
          effects.replace('data-anim="dilate"', 'data-anim="dilate" data-amplitude="0.6"'),
        ),
      ),
    /data-amplitude/,
  );
  const grouped = parseStage(
    svg(
      basePaths,
      '<g id="streams" stroke="#fff" data-anim="flow"><path d="M100 700H400"/><path d="M100 750H400"/></g>' +
        '<circle cx="200" cy="950" r="8" data-anim="pulse"/><circle cx="400" cy="950" r="8" data-anim="dilate"/>',
    ),
  );
  const html = renderToStaticMarkup(
    createElement(ObjectScene, { scene: { ref, stage: grouped.root }, frame: 15 }),
  );
  assert.equal((html.match(/stroke-dasharray="0.22 0.12"/g) ?? []).length, 2);
});

test('signed 1.7.2 pulse, move and draw frames play exactly as the old renderer produced them', (t) => {
  // These bytes and frame snapshots were generated by the actual 1.7.2 commit,
  // not by the current parser or renderer.
  const dir = path.join('tests', 'fixtures', 'legacy-motion');
  const old = JSON.parse(fs.readFileSync(path.join(dir, 'v1.7.2.json'), 'utf8')) as {
    sourceCommit: string;
    narration: string;
    ref: MotionRef;
    frames: Record<string, string>;
  };
  assert.equal(old.sourceCommit, '3a32f6d89345db482c693b0330cf8731545cab4c');
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'studio-legacy-pulse-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  fs.mkdirSync(path.join(root, 'media', 'motion'), { recursive: true });
  fs.copyFileSync(
    path.join(dir, 'v1.7.2.svg'),
    path.join(root, 'media', 'motion', `${old.ref.digest}.svg`),
  );
  const scene = motionFrame(root, old.ref, old.narration);
  for (const [frame, expected] of Object.entries(old.frames)) {
    const actual = renderToStaticMarkup(
      createElement(ObjectScene, { scene, frame: Number(frame) }),
    );
    assert.equal(actual, expected, `v1.7.2 frame ${frame} changed`);
  }
  // The motion version is signed; a tampered reference cannot opt into v2.
  assert.throws(
    () => motionFrame(root, { ...old.ref, kind: 'objects-v2' }, old.narration),
    /doğrulanamadı/,
  );
  assert.match(old.frames['15'], /opacity="0\.5"/);
  assert.match(old.frames['30'], /translate\(300 0\)/); // 600px after the authored scale
});

test('new anatomical scenes forbid independent move, even for unlabelled geometry; normal animal movement remains legal', () => {
  const moved = `${basePaths}<circle cx="450" cy="700" r="50" data-anim="move" data-dx="40"/>`;
  const stage = parseStage(svg(moved)).root;
  assert.throws(
    () => validateNewStage(stage, { topic: 'Göz bebeği neden büyür?' }),
    /bağımsız move alamaz/,
  );
  assert.throws(
    () => validateNewStage(stage, { topic: 'Kalp nasıl çalışır?' }),
    /bağımsız move alamaz/,
  );
  assert.doesNotThrow(() =>
    validateNewStage(stage, { topic: 'Karıncalar', narration: 'Karıncalar gözden kaybolur.' }),
  );
  for (const id of ['pupil', 'left-iris', 'rightKidney', 'kalp', 'goz-bebegi']) {
    const marked = parseStage(
      svg(
        `${basePaths}<g id="${id}"><circle cx="450" cy="700" r="50" data-anim="move" data-dx="40"/></g>`,
      ),
    ).root;
    assert.throws(() => validateNewStage(marked, { topic: 'Bilim' }), /bağımsız move alamaz/, id);
  }
  const dilation = parseStage(
    svg(`${basePaths}<circle id="pupil" cx="450" cy="700" r="50" data-anim="dilate"/>`),
  ).root;
  assert.doesNotThrow(() => validateNewStage(dilation, { topic: 'Göz bebeği' }));
  // An independently moving definition could otherwise bypass scale-aware checks
  // when reused by several transformed <use> instances.
  const defs =
    '<defs><g id="subject-main"><circle cx="20" cy="20" r="10" data-anim="move" data-dx="80"/></g></defs>';
  const definedMove = parseStage(
    svg(basePaths).replace('<g id="layer-bg">', defs + '<g id="layer-bg">'),
  ).root;
  assert.throws(
    () => validateNewStage(definedMove, { topic: 'Bilim' }),
    /defs içindeki nesnelere move verme/,
  );
});

test('old signed anatomy with independent move still verifies and reopens without revalidating new rules', (t) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'studio-old-anatomy-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const narration = 'Göz bebeği ışığa tepki verir.';
  const oldEffects = [1, 2, 3]
    .map((i) => `<circle cx="${i * 160}" cy="900" r="8" data-anim="fall"/>`)
    .join('');
  const old = svg(
    `${basePaths}<circle id="pupil" cx="450" cy="700" r="50" data-anim="move" data-dx="60"/>`,
    oldEffects,
  );
  const saved = saveMotion(
    root,
    {
      kind: 'objects-v1',
      title: 'Göz Bebeği',
      narrationHash: hash(narration),
      provider: 'openrouter',
      model: 'old-model',
    },
    old,
  );
  const frame = motionFrame(root, saved, narration);
  assert.equal(frame.ref.digest, saved.digest);
  assert.match(
    fs.readFileSync(path.join(root, 'media', 'motion', `${saved.digest}.svg`), 'utf8'),
    /<circle\b(?=[^>]*id="pupil")(?=[^>]*data-anim="move")/,
  );
  assert.throws(() => validateNewStage(frame.stage, { narration }), /bağımsız move alamaz/);
});

